const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {chromium} = require(process.env.PLAYWRIGHT_CORE_PATH || 'playwright');

(async () => {
  const browser = await chromium.launch({headless: true, ...(process.env.BROWSER_EXECUTABLE ? {executablePath: process.env.BROWSER_EXECUTABLE} : {})});
  try {
    const context = await browser.newContext({viewport: {width: 1440, height: 1000}, reducedMotion: 'reduce'});
    // Deterministic offline map fallback; live map is inspected separately.
    await context.route('https://unpkg.com/**', route => route.abort());
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('dialog', dialog => {errors.push('Unexpected dialog: '+dialog.message()); dialog.dismiss();});
    const root = page.locator('main');
    await page.goto(process.env.BROWSER_UI_URL+'/#discover');
    await root.getByRole('heading', {name: 'Discover', exact: true}).waitFor();
    await root.getByRole('link', {name: 'Browser <img src=x onerror=alert(1)> night'}).waitFor();
    assert.equal(await root.locator('img[onerror]').count(), 0);
    await page.getByRole('searchbox').fill('absent-query');
    await page.getByRole('button', {name: 'Search Discover'}).click();
    await root.getByText('No upcoming events match.', {exact: false}).waitFor();
    await page.goto(process.env.BROWSER_UI_URL+'/#genre/1');
    await root.locator('details').first().waitFor();
    await page.goto(process.env.BROWSER_UI_URL+'/#discover');
    await root.getByRole('heading', {name: 'Artists & DJs'}).waitFor();
    await root.locator('a[href^="#artist/"]').first().click();
    await root.getByRole('heading', {name: 'Tracks & sets'}).waitFor();
    await page.goto(process.env.BROWSER_UI_URL+'/#event/1');
    await root.getByRole('heading', {name: 'The sound'}).waitFor();
    await root.getByText('Safe fixture description').waitFor();
    await page.goto(process.env.BROWSER_UI_URL+'/#near');
    await root.getByText('The map could not load.', {exact: false}).waitFor();
    await root.getByRole('link', {name: 'Browser <img src=x onerror=alert(1)> night'}).waitFor();
    const artifacts = path.resolve('tools/browser/artifacts');
    fs.mkdirSync(artifacts, {recursive: true});
    await page.goto(process.env.BROWSER_UI_URL+'/#discover');
    await root.getByRole('heading', {name: 'Artists & DJs'}).waitFor();
    await page.screenshot({path: path.join(artifacts, 'discover-desktop.png'), fullPage: true});
    await page.setViewportSize({width: 390, height: 844});
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile page must not overflow horizontally');
    await page.screenshot({path: path.join(artifacts, 'discover-mobile.png'), fullPage: true});
    await page.setViewportSize({width: 1440, height: 1000});
    async function go(target, route) {await target.evaluate(value => {location.hash = value;}, route);}
    async function signIn(target, username) {
      await target.goto(process.env.BROWSER_UI_URL+'/#login');
      await target.getByLabel('Username', {exact: true}).fill(username);
      await target.getByLabel('Password', {exact: true}).fill(process.env.BROWSER_PASSWORD);
      await target.locator('main').getByRole('button', {name: 'Log in', exact: true}).click();
      await target.getByRole('button', {name: 'Save profile'}).waitFor();
    }
    await signIn(page, 'browserowner');
    await page.getByLabel('Bio', {exact: true}).fill('My musical profile');
    await page.getByRole('button', {name: 'Save profile'}).click();
    await root.getByText('Saved.', {exact: true}).waitFor();
    await go(page, 'create-event');
    await page.getByLabel('Event title', {exact: true}).fill('Browser created event');
    await page.getByLabel('Venue', {exact: true}).selectOption({label: 'Browser venue · Europe/Madrid'});
    const future = new Date(Date.now()+4*86400000).toISOString().slice(0,10);
    await page.getByLabel('Start (venue local time)', {exact: true}).fill(future+'T20:00');
    await page.getByLabel('End (venue local time)', {exact: true}).fill(future+'T23:00');
    await page.getByLabel('Description', {exact: true}).fill('Created through the static event form');
    await page.getByLabel('Genres (choose at least one)', {exact: true}).selectOption({label: 'House'});
    await page.getByRole('button', {name: 'Create event', exact: true}).click();
    await root.getByRole('heading', {name: 'Event saved'}).waitFor();
    await go(page, 'event/1');
    await page.getByRole('button', {name: 'Follow event', exact: true}).click();
    await root.getByText('Saved.', {exact: true}).waitFor();
    await go(page, 'my-events');
    await root.getByRole('heading', {name: 'Your listings'}).waitFor();
    await root.getByRole('heading', {name: 'Browser created event'}).waitFor();
    await go(page, 'create-group/1');
    await page.getByLabel('Group name', {exact: true}).fill('Browser private group');
    await page.getByLabel('Description', {exact: true}).fill('A real two-service browser flow');
    await page.getByLabel('Who can join?', {exact: true}).selectOption('approval_required');
    await page.getByRole('button', {name: 'Create group', exact: true}).click();
    await root.getByRole('heading', {name: 'Chat', exact: true}).waitFor();
    const groupId = (await page.evaluate(() => location.hash)).split('/')[1];
    const guestContext = await browser.newContext({viewport: {width: 390, height: 844}});
    await guestContext.route('https://unpkg.com/**', route => route.abort());
    const guest = await guestContext.newPage();
    guest.on('pageerror', error => errors.push(error.message));
    await signIn(guest, 'browserguest');
    await go(guest, 'group/'+groupId);
    await guest.getByRole('button', {name: 'Request to join', exact: true}).click();
    await guest.locator('main').getByText('Saved.', {exact: true}).waitFor();
    await go(page, 'groups');
    await root.getByRole('heading', {name: 'Requests', exact: true}).waitFor();
    await go(page, 'group/'+groupId);
    await page.getByRole('button', {name: 'Approve', exact: true}).click();
    await root.getByText('Request approved.', {exact: true}).waitFor();
    await go(guest, 'groups');
    await guest.locator('main').getByRole('heading', {name: 'Browser private group', exact: true}).waitFor();
    await go(guest, 'group/'+groupId);
    await guest.getByLabel('Message', {exact: true}).fill('Hello <script>alert(1)</script> from guest');
    await guest.getByRole('button', {name: 'Send message', exact: true}).click();
    await page.getByRole('log').getByText('Hello <script>alert(1)</script> from guest', {exact: true}).waitFor();
    await guest.locator('main').getByText('Saved.', {exact: true}).waitFor();
    assert.equal(await page.getByRole('log').locator('script').count(), 0);
    await page.screenshot({path: path.join(artifacts, 'group-desktop.png'), fullPage: true});
    await guest.screenshot({path: path.join(artifacts, 'group-mobile.png'), fullPage: true});
    assert(await guest.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await guest.getByRole('button', {name: 'Log out', exact: true}).click();
    await guest.locator('main').getByRole('heading', {name: 'Log in', exact: true}).waitFor();
    assert.equal(await guest.getByText('Hello <script>alert(1)</script> from guest', {exact: true}).count(), 0);
    assert.equal(await guest.evaluate(() => localStorage.length + sessionStorage.length), 0);
    await guestContext.close();
    await page.reload();
    await root.getByRole('heading', {name: 'Log in to continue', exact: true}).waitFor();
    assert.equal(await page.getByRole('log').count(), 0);
    assert.deepEqual(errors, []);
    assert.equal(await page.evaluate(() => localStorage.length + sessionStorage.length), 0);
    await context.close();
    console.log('Browser checks passed: public views, account/profile, event form/follow, private-group request/approval, cross-service chat, safe text, logout/reload isolation and desktop/mobile.');
  } finally {await browser.close();}
})().catch(error => {console.error(error); process.exitCode = 1;});
